using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;
using SharpFFI.Generators.Core;

namespace SharpFFI.Generators.C;

[Generator(LanguageNames.CSharp)]
public class FixedListGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var fixedListDeclarations = context.SyntaxProvider.ForAttributeWithMetadataName(
            fullyQualifiedMetadataName: FixedListAttributeData.AttributeFullName,
            predicate: static (syntaxNode, _) => syntaxNode is StructDeclarationSyntax structDeclaration && TypeModifierValidator.FixedList.IsValid(structDeclaration),
            transform: static (context, _) =>
            {
                var symbol = (INamedTypeSymbol)context.TargetSymbol;
                var attribute = FixedListAttributeData.FromAttributeData(context.Attributes[0]);

                return new FixedListGenerationContext(
                    symbol.GetNamespace(),
                    symbol.GetRawName(),
                    symbol.GetTypeDeclarationName(),
                    symbol.GetHintName("FixedList"),
                    attribute);
            });

        context.RegisterSourceOutput(fixedListDeclarations, static (productionContext, context) => productionContext.AddSource(context.HintName, SourceText.From(GenerateSourceCode(context), Encoding.UTF8)));
    }

    private static string GenerateSourceCode(FixedListGenerationContext context)
    {
        var rawName = context.RawStructName;
        var name = context.StructName;
        var capacity = context.FixedListAttribute.Capacity;
        var builder = new SourceCodeBuilder();

        builder.AppendAutoGenerated()
               .AppendNullableEnable()
               .AppendWarningDisable("CS9084")
               .AppendUsings("System", "System.Diagnostics", "System.Runtime.InteropServices", "System.Runtime.CompilerServices");

        using (builder.BeginNamespaceScope(context.StructNamespace))
        {
            builder.AppendLine("[DebuggerDisplay(\"Count = {_count}, Capacity = {Capacity}\")]")
                   .AppendLine("[StructLayout(LayoutKind.Sequential)]");

            using (builder.BeginTypeScope("struct", name))
            {
                builder.AppendBlock($$"""
                    public const int Capacity = {{capacity}};

                    private int _count;

                    private Buffer _buffer;

                    public static {{name}} Empty
                    {
                        [MethodImpl(MethodImplOptions.AggressiveInlining)]
                        get => default;
                    }

                    [MethodImpl(MethodImplOptions.AggressiveInlining)]
                    public {{rawName}}(ReadOnlySpan<T> items) : this() => Append(items);

                    public readonly int Count
                    {
                        [MethodImpl(MethodImplOptions.AggressiveInlining)]
                        get => _count;
                    }

                    public readonly bool IsEmpty
                    {
                        [MethodImpl(MethodImplOptions.AggressiveInlining)]
                        get => _count == 0;
                    }

                    public readonly bool IsFull
                    {
                        [MethodImpl(MethodImplOptions.AggressiveInlining)]
                        get => _count == Capacity;
                    }

                    public ref T this[int index]
                    {
                        [MethodImpl(MethodImplOptions.AggressiveInlining)]
                        get => ref AsSpan()[index];
                    }

                    [MethodImpl(MethodImplOptions.AggressiveInlining)]
                    public ref T Append()
                    {
                        if ((uint)_count >= (uint)Capacity)
                            ThrowCapacityExceeded();

                        var index = _count;
                        _count = index + 1;
                        return ref MemoryMarshal.CreateSpan(ref _buffer.Item0, Capacity)[index];
                    }

                    [MethodImpl(MethodImplOptions.AggressiveInlining)]
                    public void Append(in T item)
                    {
                        if ((uint)_count >= (uint)Capacity)
                            ThrowCapacityExceeded();

                        Unsafe.Add(ref _buffer.Item0, (IntPtr)(uint)_count) = item;
                        _count++;
                    }

                    [MethodImpl(MethodImplOptions.AggressiveInlining)]
                    public void Append(ReadOnlySpan<T> items)
                    {
                        if ((uint)items.Length > (uint)(Capacity - _count))
                            ThrowCapacityExceeded();

                        ref var destination = ref Unsafe.Add(ref _buffer.Item0, (IntPtr)(uint)_count);
                        items.CopyTo(MemoryMarshal.CreateSpan(ref destination, items.Length));
                        _count += items.Length;
                    }

                    [MethodImpl(MethodImplOptions.AggressiveInlining)]
                    public Span<T> AppendUninitialized(int count)
                    {
                        if ((uint)count > (uint)(Capacity - _count))
                            ThrowCapacityExceeded();

                        ref var destination = ref Unsafe.Add(ref _buffer.Item0, (IntPtr)(uint)_count);
                        _count += count;

                        var span = MemoryMarshal.CreateSpan(ref destination, count);

                        if (RuntimeHelpers.IsReferenceOrContainsReferences<T>())
                            span.Clear();

                        return span;
                    }

                    [MethodImpl(MethodImplOptions.AggressiveInlining)]
                    public void Insert(int index, in T item)
                    {
                        if ((uint)index > (uint)_count)
                            ThrowIndexOutOfRange();

                        if ((uint)_count >= (uint)Capacity)
                            ThrowCapacityExceeded();

                        var moveCount = _count - index;
                        if (moveCount > 0)
                        {
                            ref var src = ref Unsafe.Add(ref _buffer.Item0, (IntPtr)(uint)index);
                            ref var dst = ref Unsafe.Add(ref _buffer.Item0, (IntPtr)(uint)(index + 1));
                            MemoryMarshal.CreateSpan(ref src, moveCount).CopyTo(MemoryMarshal.CreateSpan(ref dst, moveCount));
                        }

                        Unsafe.Add(ref _buffer.Item0, (IntPtr)(uint)index) = item;
                        _count++;
                    }

                    [MethodImpl(MethodImplOptions.AggressiveInlining)]
                    public void Insert(int index, ReadOnlySpan<T> items)
                    {
                        if ((uint)index > (uint)_count)
                            ThrowIndexOutOfRange();

                        if ((uint)(_count + items.Length) > (uint)Capacity)
                            ThrowCapacityExceeded();

                        if (items.IsEmpty)
                            return;

                        var moveCount = _count - index;
                        if (moveCount > 0)
                        {
                            ref var src = ref Unsafe.Add(ref _buffer.Item0, (IntPtr)(uint)index);
                            ref var dst = ref Unsafe.Add(ref _buffer.Item0, (IntPtr)(uint)(index + items.Length));
                            MemoryMarshal.CreateSpan(ref src, moveCount).CopyTo(MemoryMarshal.CreateSpan(ref dst, moveCount));
                        }

                        ref var destination = ref Unsafe.Add(ref _buffer.Item0, (IntPtr)(uint)index);
                        items.CopyTo(MemoryMarshal.CreateSpan(ref destination, items.Length));
                        _count += items.Length;
                    }

                    [MethodImpl(MethodImplOptions.AggressiveInlining)]
                    public T Pop()
                    {
                        if ((uint)_count == 0)
                            ThrowIndexOutOfRange();

                        var index = _count - 1;
                        _count = index;
                        ref var item = ref Unsafe.Add(ref _buffer.Item0, (IntPtr)(uint)index);
                        var result = item;

                        if (RuntimeHelpers.IsReferenceOrContainsReferences<T>())
                            item = default!;

                        return result;
                    }

                    [MethodImpl(MethodImplOptions.AggressiveInlining)]
                    public void Pop(int count)
                    {
                        if ((uint)count > (uint)_count)
                            ThrowIndexOutOfRange();

                        _count -= count;

                        if (!RuntimeHelpers.IsReferenceOrContainsReferences<T>())
                            return;

                        ref var start = ref Unsafe.Add(ref _buffer.Item0, (IntPtr)(uint)_count);
                        MemoryMarshal.CreateSpan(ref start, count).Clear();
                    }

                    [MethodImpl(MethodImplOptions.AggressiveInlining)]
                    public void RemoveAt(int index)
                    {
                        if ((uint)index >= (uint)_count)
                            ThrowIndexOutOfRange();

                        var moveCount = _count - index - 1;
                        if (moveCount > 0)
                        {
                            ref var src = ref Unsafe.Add(ref _buffer.Item0, (IntPtr)(uint)(index + 1));
                            ref var dst = ref Unsafe.Add(ref _buffer.Item0, (IntPtr)(uint)index);
                            MemoryMarshal.CreateSpan(ref src, moveCount).CopyTo(MemoryMarshal.CreateSpan(ref dst, moveCount));
                        }

                        var lastIndex = _count - 1;
                        _count = lastIndex;

                        if (RuntimeHelpers.IsReferenceOrContainsReferences<T>())
                            Unsafe.Add(ref _buffer.Item0, (IntPtr)(uint)lastIndex) = default!;
                    }

                    [MethodImpl(MethodImplOptions.AggressiveInlining)]
                    public T RemoveSwap(int index)
                    {
                        if ((uint)index >= (uint)_count)
                            ThrowIndexOutOfRange();

                        var lastIndex = _count - 1;
                        _count = lastIndex;
                        ref var target = ref Unsafe.Add(ref _buffer.Item0, (IntPtr)(uint)index);
                        ref var last = ref Unsafe.Add(ref _buffer.Item0, (IntPtr)(uint)lastIndex);
                        var removed = target;

                        target = last;

                        if (RuntimeHelpers.IsReferenceOrContainsReferences<T>())
                            last = default!;

                        return removed;
                    }

                    [MethodImpl(MethodImplOptions.AggressiveInlining)]
                    public void Clear()
                    {
                        if (RuntimeHelpers.IsReferenceOrContainsReferences<T>())
                            AsSpan().Clear();

                        _count = 0;
                    }

                    [MethodImpl(MethodImplOptions.AggressiveInlining)]
                    public Span<T> AsSpan() => MemoryMarshal.CreateSpan(ref _buffer.Item0, _count);

                    [MethodImpl(MethodImplOptions.AggressiveInlining)]
                    public readonly ReadOnlySpan<T> AsReadOnlySpan() => MemoryMarshal.CreateSpan(ref Unsafe.AsRef(in _buffer.Item0), _count);

                    [MethodImpl(MethodImplOptions.AggressiveInlining)]
                    public Span<T> Slice(int start) => AsSpan().Slice(start);

                    [MethodImpl(MethodImplOptions.AggressiveInlining)]
                    public Span<T> Slice(int start, int length) => AsSpan().Slice(start, length);

                    [MethodImpl(MethodImplOptions.AggressiveInlining)]
                    public readonly void CopyTo(Span<T> destination) => AsReadOnlySpan().CopyTo(destination);

                    [MethodImpl(MethodImplOptions.AggressiveInlining)]
                    public readonly bool TryCopyTo(Span<T> destination) => AsReadOnlySpan().TryCopyTo(destination);

                    [MethodImpl(MethodImplOptions.AggressiveInlining)]
                    public static implicit operator ReadOnlySpan<T>(in {{name}} list) => list.AsReadOnlySpan();

                    [MethodImpl(MethodImplOptions.AggressiveInlining)]
                    public readonly ReadOnlySpan<T>.Enumerator GetEnumerator() => AsReadOnlySpan().GetEnumerator();

                    public readonly override string ToString() => $"{{rawName}}<{typeof(T).Name}>[{_count}/{Capacity}]";

                    private static void ThrowIndexOutOfRange() => throw new IndexOutOfRangeException("Index was outside the bounds of the {{rawName}}<T>.");

                    private static void ThrowCapacityExceeded() => throw new InvalidOperationException("Item count exceeds the capacity of {{rawName}}<T>.");
                    """);

                builder.AppendLine()
                       .AppendFixedBuffer(capacity);
            }
        }

        return builder.ToString();
    }

    private readonly record struct FixedListGenerationContext(
        string StructNamespace,
        string RawStructName,
        string StructName,
        string HintName,
        FixedListAttributeData FixedListAttribute);
}
