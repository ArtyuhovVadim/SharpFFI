using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;
using SharpFFI.Annotations;
using SharpFFI.Generators.Core;

namespace SharpFFI.Generators.C;

[Generator(LanguageNames.CSharp)]
public class HandleGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var handleDeclarations = context.SyntaxProvider.ForAttributeWithMetadataName(
            fullyQualifiedMetadataName: "SharpFFI.Annotations.HandleAttribute",
            predicate: static (syntaxNode, _) => syntaxNode is StructDeclarationSyntax decl && decl.Modifiers.Any(SyntaxKind.PartialKeyword),
            transform: static (context, _) =>
            {
                var symbol = (INamedTypeSymbol)context.TargetSymbol;
                var attribute = context.Attributes[0].ToHandleAttribute();

                var name = symbol.Name;
                var @namespace = symbol.ContainingNamespace.IsGlobalNamespace ? string.Empty : symbol.ContainingNamespace.ToDisplayString();
                var isRef = symbol.IsRefLikeType;

                return new HandleGenerationContext(@namespace, name, isRef, attribute);
            });

        context.RegisterSourceOutput(handleDeclarations, static (productionContext, handleContext) =>
            productionContext.AddSource($"{handleContext.StructName}.Handle.g.cs", SourceText.From(GenerateHandleSourceCode(handleContext), Encoding.UTF8)));
    }

    private static string GenerateHandleSourceCode(HandleGenerationContext context)
    {
        var builder = new SourceCodeBuilder();

        builder.AppendAutoGenerated()
               .AppendLine()
               .AppendNullableEnable();

        if (context.IsRef)
            builder.AppendWarningDisable("CS0809");

        builder.AppendLine()
               .AppendUsing("System")
               .AppendUsing("System.Runtime.InteropServices")
               .AppendUsing("System.Runtime.CompilerServices");

        if (context.IsRef)
            builder.AppendUsing("System.ComponentModel");

        builder.AppendLine();

        if (context.IsGlobalNamespace)
        {
            GenerateHandleStructSourceCode(builder, context);
        }
        else
        {
            builder.AppendNamespace(context.StructNamespace);

            using (builder.BeginScope())
            {
                GenerateHandleStructSourceCode(builder, context);
            }
        }

        return builder.ToString();
    }

    private static void GenerateHandleStructSourceCode(SourceCodeBuilder builder, HandleGenerationContext context)
    {
        builder.AppendLine("[StructLayout(LayoutKind.Sequential)]")
               .AppendLine(context.IsRef
               ? $"partial struct {context.StructName}"
               : $"partial struct {context.StructName} : IEquatable<{context.StructName}>");

        using (builder.BeginScope())
        {
            builder.AppendLine("public readonly nint Handle;")
                   .AppendLine();

            if (context.HandleAttribute.Ctor != DefaultHandleCtor.None)
            {
                var ctorCode = context.HandleAttribute.Ctor switch
                {
                    DefaultHandleCtor.Private => $"private {context.StructName}(nint handle) => Handle = handle;",
                    DefaultHandleCtor.Internal => $"internal {context.StructName}(nint handle) => Handle = handle;",
                    DefaultHandleCtor.Public => $"public {context.StructName}(nint handle) => Handle = handle;",
                    _ => throw new ArgumentOutOfRangeException()
                };

                builder.AppendAgressiveInlining()
                       .AppendLine(ctorCode)
                       .AppendLine();
            }

            builder.AppendAgressiveInlining()
                   .AppendLine($"public bool Equals({context.StructName} other) => Handle.Equals(other.Handle);")
                   .AppendLine();

            if (context.IsRef)
            {
                builder.AppendLine("[EditorBrowsable(EditorBrowsableState.Never)]")
                       .AppendLine("[Obsolete(\"Equals(object) on ref struct is not supported.\", true)]")
                       .AppendLine("public override bool Equals(object? obj) => throw new NotSupportedException();");
            }
            else
            {
                builder.AppendAgressiveInlining()
                       .AppendLine($"public override bool Equals(object? obj) => obj is {context.StructName} other && Equals(other);");
            }

            builder.AppendLine();

            if (context.IsRef)
            {
                builder.AppendLine("[EditorBrowsable(EditorBrowsableState.Never)]")
                       .AppendLine("[Obsolete(\"GetHashCode() on ref struct is not supported.\", true)]")
                       .AppendLine("public override int GetHashCode() => throw new NotSupportedException();");
            }
            else
            {
                builder.AppendAgressiveInlining()
                       .AppendLine("public override int GetHashCode() => Handle.GetHashCode();");
            }

            builder.AppendLine()
                   .AppendAgressiveInlining()
                   .AppendLine($"public static bool operator ==({context.StructName} left, {context.StructName} right) => left.Equals(right);")
                   .AppendLine()
                   .AppendAgressiveInlining()
                   .AppendLine($"public static bool operator !=({context.StructName} left, {context.StructName} right) => !left.Equals(right);");
        }
    }

    private readonly record struct HandleGenerationContext(string StructNamespace, string StructName, bool IsRef, HandleAttributeData HandleAttribute)
    {
        public bool IsGlobalNamespace => string.IsNullOrEmpty(StructNamespace);
    }
}
