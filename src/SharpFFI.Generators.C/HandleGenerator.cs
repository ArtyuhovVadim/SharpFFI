using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace SharpFFI.Generators.C;

public readonly record struct HandleGenerationContext(string StructNamespace, string StructName, bool IsRef)
{
    public bool IsGlobalNamespace => string.IsNullOrEmpty(StructNamespace);
}

[Generator(LanguageNames.CSharp)]
public class HandleGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var handleDeclarations = context.SyntaxProvider.ForAttributeWithMetadataName(
            fullyQualifiedMetadataName: "SharpFFI.Annotations.HandleAttribute",
            predicate: static (syntaxNode, _) => syntaxNode is StructDeclarationSyntax decl && decl.Modifiers.Any(SyntaxKind.PartialKeyword),
            transform: static (context, _) =>
            {
                var symbol = (INamedTypeSymbol)context.TargetSymbol;

                var name = symbol.Name;
                var @namespace = symbol.ContainingNamespace.IsGlobalNamespace ? string.Empty : symbol.ContainingNamespace.ToDisplayString();
                var isRef = symbol.IsRefLikeType;

                return new HandleGenerationContext(@namespace, name, isRef);
            });

        context.RegisterSourceOutput(handleDeclarations, static (productionContext, handleContext) =>
            productionContext.AddSource($"{handleContext.StructName}.Handle.g.cs", SourceText.From(GenerateHandleSourceCode(handleContext), Encoding.UTF8)));
    }

    private static string GenerateHandleSourceCode(HandleGenerationContext context)
    {
        var sb = new StringBuilder();

        sb.AppendLine("// <auto-generated />");
        sb.AppendLine();
        sb.AppendLine("#nullable enable");

        if (context.IsRef)
            sb.AppendLine("#pragma warning disable CS0809");

        sb.AppendLine();
        sb.AppendLine("using System;");

        if (context.IsRef)
            sb.AppendLine("using System.ComponentModel;");

        sb.AppendLine("using System.Runtime.CompilerServices;");
        sb.AppendLine();

        if (!context.IsGlobalNamespace)
        {
            sb.AppendLine($"namespace {context.StructNamespace};");
            sb.AppendLine();
        }

        sb.Append($"partial struct {context.StructName}");

        if (context.IsRef)
            sb.AppendLine();
        else
            sb.AppendLine($" : IEquatable<{context.StructName}>");

        sb.AppendLine("{");
        sb.AppendLine("    public readonly nint Handle;");
        sb.AppendLine();
        sb.AppendLine("    [MethodImpl(MethodImplOptions.AggressiveInlining)]");
        sb.AppendLine($"    public bool Equals({context.StructName} other) => Handle.Equals(other.Handle);");
        sb.AppendLine();

        if (context.IsRef)
        {
            sb.AppendLine("    [EditorBrowsable(EditorBrowsableState.Never)]");
            sb.AppendLine("    [Obsolete(\"Equals(object) on ref struct is not supported.\", true)]");
            sb.AppendLine("    public override bool Equals(object? obj) => throw new NotSupportedException();");
        }
        else
        {
            sb.AppendLine("    [MethodImpl(MethodImplOptions.AggressiveInlining)]");
            sb.AppendLine($"    public override bool Equals(object? obj) => obj is {context.StructName} other && Equals(other);");
        }

        sb.AppendLine();

        if (context.IsRef)
        {
            sb.AppendLine("    [EditorBrowsable(EditorBrowsableState.Never)]");
            sb.AppendLine("    [Obsolete(\"GetHashCode() on ref struct is not supported.\", true)]");
            sb.AppendLine("    public override int GetHashCode() => throw new NotSupportedException();");
        }
        else
        {
            sb.AppendLine("    [MethodImpl(MethodImplOptions.AggressiveInlining)]");
            sb.AppendLine($"    public override int GetHashCode() => Handle.GetHashCode();");
        }

        sb.AppendLine();
        sb.AppendLine("    [MethodImpl(MethodImplOptions.AggressiveInlining)]");
        sb.AppendLine($"    public static bool operator ==({context.StructName} left, {context.StructName} right) => left.Equals(right);");
        sb.AppendLine();
        sb.AppendLine("    [MethodImpl(MethodImplOptions.AggressiveInlining)]");
        sb.AppendLine($"    public static bool operator !=({context.StructName} left, {context.StructName} right) => !left.Equals(right);");
        sb.AppendLine("}");

        return sb.ToString();
    }
}
