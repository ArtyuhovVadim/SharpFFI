using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;
using SharpFFI.Annotations;
using SharpFFI.Generators.Core;

namespace SharpFFI.Generators.C;

[Generator(LanguageNames.CSharp)]
public class HandleGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var handleDeclarations = context.SyntaxProvider.ForAttributeWithMetadataName(
            fullyQualifiedMetadataName: HandleAttributeData.AttributeFullName,
            predicate: static (syntaxNode, _) => syntaxNode is StructDeclarationSyntax structDeclaration && TypeModifierValidator.Handle.IsValid(structDeclaration),
            transform: static (context, _) =>
            {
                var symbol = (INamedTypeSymbol)context.TargetSymbol;
                var attribute = HandleAttributeData.FromAttributeData(context.Attributes[0]);

                return new HandleGenerationContext(
                    symbol.GetNamespace(),
                    symbol.GetTypeDeclarationName(),
                    symbol.GetHintName("Handle"),
                    symbol.IsRefLikeType,
                    attribute);
            });

        context.RegisterSourceOutput(handleDeclarations, static (productionContext, context) => productionContext.AddSource(context.HintName, SourceText.From(GenerateSourceCode(context), Encoding.UTF8)));
    }

    private static string GenerateSourceCode(HandleGenerationContext context)
    {
        var name = context.StructName;
        var builder = new SourceCodeBuilder();

        builder.AppendAutoGenerated()
               .AppendNullableEnable();

        if (context.IsRef)
            builder.AppendWarningDisable("CS0809");

        builder.AppendUsings("System", "System.Runtime.InteropServices", "System.Runtime.CompilerServices");

        if (context.IsRef)
            builder.AppendUsing("System.ComponentModel").AppendLine();

        using (builder.BeginNamespaceScope(context.StructNamespace))
        {
            builder.AppendLine("[StructLayout(LayoutKind.Sequential)]");

            var typeDeclaration = context.IsRef ? name : $"{name} : IEquatable<{name}>";
            using (builder.BeginTypeScope("struct", typeDeclaration))
            {
                builder.AppendBlock($"""
                    public static {name} Null => default;

                    public readonly IntPtr Handle;
                    """);

                builder.AppendLine();

                if (context.HandleAttribute.Ctor != DefaultHandleCtor.None)
                {
                    var visibility = context.HandleAttribute.Ctor switch
                    {
                        DefaultHandleCtor.Private => "private",
                        DefaultHandleCtor.Internal => "internal",
                        DefaultHandleCtor.Public => "public",
                        _ => throw new ArgumentOutOfRangeException()
                    };

                    builder.AppendBlock($"""
                        [MethodImpl(MethodImplOptions.AggressiveInlining)]
                        {visibility} {name}(IntPtr handle) => Handle = handle;

                        [MethodImpl(MethodImplOptions.AggressiveInlining)]
                        public static explicit operator {name}(IntPtr handle) => new {name}(handle);
                        """);

                    builder.AppendLine();
                }

                builder.AppendBlock($"""
                    [MethodImpl(MethodImplOptions.AggressiveInlining)]
                    public static implicit operator IntPtr({name} handle) => handle.Handle;

                    [MethodImpl(MethodImplOptions.AggressiveInlining)]
                    public readonly bool Equals({name} other) => Handle.Equals(other.Handle);
                    """);

                builder.AppendLine();

                if (context.IsRef)
                {
                    builder.AppendBlock($"""
                        [MethodImpl(MethodImplOptions.AggressiveInlining)]
                        [EditorBrowsable(EditorBrowsableState.Never)]
                        [Obsolete("Equals(object) on ref struct is not supported.", true)]
                        public override bool Equals(object? obj) => throw new NotSupportedException();
                        """);
                }
                else
                {
                    builder.AppendInlined($"public override bool Equals(object? obj) => obj is {name} other && Equals(other);");
                }

                builder.AppendLine();

                if (context.IsRef)
                {
                    builder.AppendBlock($"""
                        [MethodImpl(MethodImplOptions.AggressiveInlining)]
                        [EditorBrowsable(EditorBrowsableState.Never)]
                        [Obsolete("GetHashCode() on ref struct is not supported.", true)]
                        public override int GetHashCode() => throw new NotSupportedException();
                        """);
                }
                else
                {
                    builder.AppendInlined("public override int GetHashCode() => Handle.GetHashCode();");
                }

                builder.AppendLine()
                       .AppendEqualityOperators(name);
            }
        }

        return builder.ToString();
    }

    private readonly record struct HandleGenerationContext(
        string StructNamespace,
        string StructName,
        string HintName,
        bool IsRef,
        HandleAttributeData HandleAttribute);
}
