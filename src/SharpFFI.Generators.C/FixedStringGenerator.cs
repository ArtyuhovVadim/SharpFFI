#nullable enable

using System.Text;
using System.Text.RegularExpressions;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;
using SharpFFI.Generators.Core;

namespace SharpFFI.Generators.C;

public readonly record struct FixedStringGenerationContext(string StructNamespace, string StructName, int Size, bool IsReadOnly, Location? Location, DiagnosticDescriptor? Diagnostic)
{
    public bool IsGlobalNamespace => string.IsNullOrEmpty(StructNamespace);

    public bool Equals(FixedStringGenerationContext other) =>
        StructNamespace == other.StructNamespace &&
        StructName == other.StructName &&
        Size == other.Size &&
        IsReadOnly == other.IsReadOnly &&
        EqualityComparer<DiagnosticDescriptor?>.Default.Equals(Diagnostic, other.Diagnostic);

    public override int GetHashCode() => HashCode.Combine(StructNamespace, StructName, Size, IsReadOnly, Diagnostic);
}

[Generator(LanguageNames.CSharp)]
public class FixedStringGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var fixedStringDeclarations = context.SyntaxProvider.ForAttributeWithMetadataName(
            fullyQualifiedMetadataName: "SharpFFI.Annotations.FixedStringAttribute",
            predicate: static (syntaxNode, _) => syntaxNode is StructDeclarationSyntax decl && decl.Modifiers.Any(SyntaxKind.PartialKeyword),
            transform: static (context, _) =>
            {
                var symbol = (INamedTypeSymbol)context.TargetSymbol;

                var name = symbol.Name;
                var @namespace = symbol.ContainingNamespace.IsGlobalNamespace ? string.Empty : symbol.ContainingNamespace.ToDisplayString();
                var location = symbol.Locations.FirstOrDefault();

                var match = Regex.Match(name, @"^(ReadOnly)?Utf8FixedCString(?<size>\d+)$");

                var isReadOnly = match.Groups[1].Success;

                if (!match.Success || !int.TryParse(match.Groups["size"].Value, out var size) || size <= 0)
                {
                    return new FixedStringGenerationContext(string.Empty, name, 0, false, location, DiagnosticDescriptors.InvalidNameError);
                }

                if (symbol.IsRefLikeType)
                {
                    return new FixedStringGenerationContext(string.Empty, name, 0, false, location, DiagnosticDescriptors.RefNotAllowedError);
                }

                return new FixedStringGenerationContext(@namespace, name, size, isReadOnly, null, null);
            });

        context.RegisterSourceOutput(fixedStringDeclarations, static (productionContext, fixedStringContext) =>
        {
            if (fixedStringContext is { Diagnostic: not null, Location: not null })
                productionContext.ReportDiagnostic(Diagnostic.Create(fixedStringContext.Diagnostic, fixedStringContext.Location, fixedStringContext.StructName));
            else
                productionContext.AddSource($"{fixedStringContext.StructName}.FixedString.g.cs", SourceText.From(GenerateFixedStringSourceCode(fixedStringContext), Encoding.UTF8));
        });
    }

    private static string GenerateFixedStringSourceCode(FixedStringGenerationContext context)
    {
        var builder = new SourceCodeBuilder();

        builder.AppendAutoGenerated()
               .AppendLine()
               .AppendNullableEnable()
               .AppendLine()
               .AppendUsing("System")
               .AppendUsing("System.Text")
               .AppendUsing("System.Diagnostics")
               .AppendUsing("System.Runtime.InteropServices")
               .AppendUsing("System.Runtime.CompilerServices")
               .AppendUsing("SharpFFI.Primitives.Extensions")
               .AppendUsing("SharpFFI.Primitives.Utf8")
               .AppendLine();

        if (context.IsGlobalNamespace)
        {
            GenerateFixedStringStructSourceCode(builder, context);
        }
        else
        {
            builder.AppendNamespace(context.StructNamespace);

            using (builder.BeginScope())
            {
                GenerateFixedStringStructSourceCode(builder, context);
            }
        }

        return builder.ToString();
    }

    private static void GenerateFixedStringStructSourceCode(SourceCodeBuilder builder, FixedStringGenerationContext context)
    {
        builder.AppendLine("[DebuggerDisplay(\"{ToString(),raw}\")]")
               .AppendLine("[StructLayout(LayoutKind.Sequential)]")
               .AppendLine($"unsafe partial struct {context.StructName}");

        using (builder.BeginScope())
        {
            builder.AppendLine($"public const int Size = {context.Size};")
                   .AppendLine()
                   .AppendLine("private fixed byte _buffer[Size];")
                   .AppendLine()
                   .AppendLine("private byte* Pointer");

            using (builder.BeginScope())
            {
                builder.AppendAgressiveInlining()
                       .AppendLine("get");

                using (builder.BeginScope())
                {
                    builder.AppendLine("fixed (byte* bufferPtr = _buffer)");

                    using (builder.BeginScope())
                    {
                        builder.AppendLine("return bufferPtr;");
                    }
                }
            }

            builder.AppendLine()
                   .AppendLine($"public {context.StructName}(string? value)");

            using (builder.BeginScope())
            {
                builder.AppendLine("if (string.IsNullOrEmpty(value))");

                using (builder.BeginScope())
                {
                    builder.AppendLine("Pointer[0] = (byte)'\\0';")
                           .AppendLine("return;");
                }

                builder.AppendLine()
                       .AppendLine("fixed (char* valuePtr = value)");

                using (builder.BeginScope())
                {
                    builder.AppendLine("int bytesWritten = Encoding.UTF8.GetBytes(valuePtr, value.Length, Pointer, Size - 1);")
                           .AppendLine("Pointer[bytesWritten] = (byte)'\\0';");
                }
            }

            builder.AppendLine()
                   .AppendLine($"public {context.StructName}(ReadOnlySpan<byte> value)");

            using (builder.BeginScope())
            {
                builder.AppendLine("if (value.IsEmpty)");
                using (builder.BeginScope())
                {
                    builder.AppendLine("Pointer[0] = (byte)'\\0';")
                           .AppendLine("return;");
                }

                builder.AppendLine()
                       .AppendLine("var copyLength = Math.Min(value.Length, Size - 1);")
                       .AppendLine("var destination = new Span<byte>(Pointer, Size);")
                       .AppendLine("value.CopyTo(destination);")
                       .AppendLine()
                       .AppendLine("Pointer[copyLength] = (byte)'\\0';");
            }

            builder.AppendLine()
                   .AppendLine("private int Length");

            using (builder.BeginScope())
            {
                builder.AppendAgressiveInlining()
                       .AppendLine("get");

                using (builder.BeginScope())
                {
                    builder.AppendLine("var zeroIndex = new ReadOnlySpan<byte>(Pointer, Size).IndexOf((byte)0);")
                           .AppendLine("return zeroIndex == -1 ? Size : zeroIndex;");
                }
            }

            builder.AppendLine()
                   .AppendLine("public bool IsEmpty");

            using (builder.BeginScope())
            {
                builder.AppendAgressiveInlining()
                       .AppendLine("get => Pointer[0] == (byte)'\\0';");
            }

            builder.AppendLine();

            builder.AppendLine(context.IsReadOnly ? "public byte this[int index]" : "public ref byte this[int index]");

            using (builder.BeginScope())
            {
                builder.AppendAgressiveInlining()
                       .AppendLine(context.IsReadOnly ? "get => Pointer[index];" : "get => ref Pointer[index];");
            }

            builder.AppendLine();

            if (!context.IsReadOnly)
            {
                builder.AppendAgressiveInlining()
                       .AppendLine("public Utf8StringView AsView() => new(Pointer, Length);")
                       .AppendLine();
            }

            builder.AppendAgressiveInlining()
                   .AppendLine("public ReadOnlyUtf8StringView AsReadOnlyView() => new(Pointer, Length);")
                   .AppendLine()
                   .AppendAgressiveInlining()
                   .AppendLine($"public bool Equals({context.StructName} other) => AsReadOnlyView().Equals(other.AsReadOnlyView());")
                   .AppendLine()
                   .AppendAgressiveInlining()
                   .AppendLine($"public override bool Equals(object? obj) => obj is {context.StructName} other && Equals(other);")
                   .AppendLine()
                   .AppendAgressiveInlining()
                   .AppendLine("public override int GetHashCode() => IsEmpty ? 0 : AsReadOnlyView().Span.GetMarvinHash();")
                   .AppendLine()
                   .AppendAgressiveInlining()
                   .AppendLine("public override string ToString() => Encoding.UTF8.GetString(AsReadOnlyView().Span);")
                   .AppendLine()
                   .AppendAgressiveInlining()
                   .AppendLine($"public static bool operator ==({context.StructName} left, {context.StructName} right) => left.Equals(right);")
                   .AppendLine()
                   .AppendAgressiveInlining()
                   .AppendLine($"public static bool operator !=({context.StructName} left, {context.StructName} right) => !left.Equals(right);");
        }
    }
}
