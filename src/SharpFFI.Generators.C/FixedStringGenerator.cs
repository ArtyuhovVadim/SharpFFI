#nullable enable

using System.Text;
using System.Text.RegularExpressions;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace SharpFFI.Generators.C;

public readonly record struct FixedStringGenerationContext(string StructNamespace, string StructName, int Size, bool IsReadOnly, Location? Location, DiagnosticDescriptor? Diagnostic)
{
    public bool IsGlobalNamespace => string.IsNullOrEmpty(StructNamespace);

    public bool Equals(FixedStringGenerationContext other) =>
        StructNamespace == other.StructNamespace &&
        StructName == other.StructName &&
        Size == other.Size &&
        IsReadOnly == other.IsReadOnly &&
        EqualityComparer<DiagnosticDescriptor?>.Default.Equals(Diagnostic, other.Diagnostic);

    public override int GetHashCode() => HashCode.Combine(StructNamespace, StructName, Size, IsReadOnly, Diagnostic);
}

[Generator(LanguageNames.CSharp)]
public class FixedStringGenerator : IIncrementalGenerator
{
    private static readonly DiagnosticDescriptor InvalidNameError = new(
        id: "FFI0001",
        title: "Invalid FixedString struct name",
        messageFormat: "The name of struct '{0}' decorated with [FixedString] must match the pattern 'Utf8FixedCString<size>' or 'ReadOnlyUtf8FixedCString<size>' (e.g., Utf8FixedCString16, ReadOnlyUtf8FixedCString67)",
        category: "Design",
        defaultSeverity: DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    private static readonly DiagnosticDescriptor RefNotAllowedError = new(
        id: "FFI0002",
        title: "Ref modifier is not allowed",
        messageFormat: "Struct '{0}' with [FixedString] cannot be a ref struct. Fixed strings must be embeddable in standard structs.",
        category: "Design",
        defaultSeverity: DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var handleDeclarations = context.SyntaxProvider.ForAttributeWithMetadataName(
            fullyQualifiedMetadataName: "SharpFFI.Annotations.FixedStringAttribute",
            predicate: static (syntaxNode, _) => syntaxNode is StructDeclarationSyntax decl && decl.Modifiers.Any(SyntaxKind.PartialKeyword),
            transform: static (context, _) =>
            {
                var symbol = (INamedTypeSymbol)context.TargetSymbol;

                var name = symbol.Name;
                var @namespace = symbol.ContainingNamespace.IsGlobalNamespace ? string.Empty : symbol.ContainingNamespace.ToDisplayString();
                var location = symbol.Locations.FirstOrDefault();

                var match = Regex.Match(name, @"^(ReadOnly)?Utf8FixedCString(?<size>\d+)$");

                var isReadOnly = match.Groups[1].Success;

                if (!match.Success || !int.TryParse(match.Groups["size"].Value, out var size) || size <= 0)
                {
                    return new FixedStringGenerationContext(string.Empty, name, 0, false, location, InvalidNameError);
                }

                if (symbol.IsRefLikeType)
                {
                    return new FixedStringGenerationContext(string.Empty, name, 0, false, location, RefNotAllowedError);
                }

                return new FixedStringGenerationContext(@namespace, name, size, isReadOnly, null, null);
            });

        context.RegisterSourceOutput(handleDeclarations, static (productionContext, fixedStringContext) =>
        {
            if (fixedStringContext is { Diagnostic: not null, Location: not null })
                productionContext.ReportDiagnostic(Diagnostic.Create(fixedStringContext.Diagnostic, fixedStringContext.Location, fixedStringContext.StructName));
            else
                productionContext.AddSource($"{fixedStringContext.StructName}.FixedString.g.cs", SourceText.From(GenerateFixedStringSourceCode(fixedStringContext), Encoding.UTF8));
        });
    }

    private static string GenerateFixedStringSourceCode(FixedStringGenerationContext context)
    {
        var sb = new StringBuilder();

        sb.AppendLine("// <auto-generated />");
        sb.AppendLine();
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("using System;");
        sb.AppendLine("using System.Text;");
        sb.AppendLine("using System.Diagnostics;");
        sb.AppendLine("using System.Runtime.InteropServices;");
        sb.AppendLine("using System.Runtime.CompilerServices;");
        sb.AppendLine("using SharpFFI.Primitives.Extensions;");
        sb.AppendLine("using SharpFFI.Primitives.Utf8;");
        sb.AppendLine();

        if (!context.IsGlobalNamespace)
        {
            sb.AppendLine($"namespace {context.StructNamespace};");
            sb.AppendLine();
        }

        sb.AppendLine("[DebuggerDisplay(\"{ToString(),raw}\")]");
        sb.AppendLine("[StructLayout(LayoutKind.Sequential)]");
        sb.AppendLine($"readonly unsafe partial struct {context.StructName}");
        sb.AppendLine("{");
        sb.AppendLine($"    public const int Size = {context.Size};");
        sb.AppendLine();
        sb.AppendLine("    private readonly FixedArray _buffer = default;");
        sb.AppendLine();
        sb.AppendLine("    private byte* Pointer => (byte*)Unsafe.AsPointer(in _buffer._element0);");
        sb.AppendLine();
        sb.AppendLine($$"""
                            public {{context.StructName}}(string? value)
                            {
                                if (string.IsNullOrEmpty(value))
                                {
                                    Pointer[0] = (byte)'\0';
                                    return;
                                }
                            
                                fixed (char* pValue = value)
                                {
                                    int bytesWritten = Encoding.UTF8.GetBytes(pValue, value.Length, Pointer, Size - 1);
                                    Pointer[bytesWritten] = (byte)'\0';
                                }
                            }
                            
                            public {{context.StructName}}(ReadOnlySpan<byte> value)
                            {
                                if (value.IsEmpty)
                                {
                                    Pointer[0] = (byte)'\0';
                                    return;
                                }
                            
                                var copyLength = Math.Min(value.Length, Size - 1);
                                var destination = new Span<byte>(Pointer, Size);
                                value.CopyTo(destination);
                            
                                Pointer[copyLength] = (byte)'\0';
                            }
                            
                            private int Length
                            {
                                [MethodImpl(MethodImplOptions.AggressiveInlining)]
                                get
                                {
                                    var zeroIndex = new ReadOnlySpan<byte>(Pointer, Size).IndexOf((byte)0);
                                    return zeroIndex == -1 ? Size : zeroIndex;
                                }
                            }
                            
                            public bool IsEmpty
                            {
                                [MethodImpl(MethodImplOptions.AggressiveInlining)]
                                get => Pointer[0] == (byte)'\0';
                            }
                        """);
        sb.AppendLine();
        sb.AppendLine(context.IsReadOnly
                      ? """
                            public byte this[int index]
                            {
                                [MethodImpl(MethodImplOptions.AggressiveInlining)]
                                get => Pointer[index];
                            }
                        """
                      : """
                            public ref byte this[int index]
                            {
                                [MethodImpl(MethodImplOptions.AggressiveInlining)]
                                get => ref Pointer[index];
                            }
                        """);
        sb.AppendLine();

        if (!context.IsReadOnly)
        {
            sb.AppendLine(
                """
                    [MethodImpl(MethodImplOptions.AggressiveInlining)]
                    public Utf8StringView AsView() => new(Pointer, Length);
                """);
            sb.AppendLine();
        }

        sb.AppendLine(
            $"""
                [MethodImpl(MethodImplOptions.AggressiveInlining)]
                public ReadOnlyUtf8StringView AsReadOnlyView() => new(Pointer, Length);
                
                [MethodImpl(MethodImplOptions.AggressiveInlining)]
                public bool Equals({context.StructName} other) => AsReadOnlyView().Equals(other.AsReadOnlyView());
                
                [MethodImpl(MethodImplOptions.AggressiveInlining)]
                public override bool Equals(object? obj) => obj is {context.StructName} other && Equals(other);
                
                [MethodImpl(MethodImplOptions.AggressiveInlining)]
                public override int GetHashCode() => IsEmpty ? 0 : AsReadOnlyView().Span.GetMarvinHash();
                
                [MethodImpl(MethodImplOptions.AggressiveInlining)]
                public override string ToString() => Encoding.UTF8.GetString(AsReadOnlyView().Span);
                
                [MethodImpl(MethodImplOptions.AggressiveInlining)]
                public static bool operator ==({context.StructName} left, {context.StructName} right) => left.Equals(right);
                
                [MethodImpl(MethodImplOptions.AggressiveInlining)]
                public static bool operator !=({context.StructName} left, {context.StructName} right) => !left.Equals(right);
            """);
        sb.AppendLine();
        sb.AppendLine("    [InlineArray(Size)]");
        sb.AppendLine("    private struct FixedArray");
        sb.AppendLine("    {");
        sb.AppendLine("        public byte _element0;");
        sb.AppendLine("    }");
        sb.AppendLine("}");

        return sb.ToString();
    }
}
