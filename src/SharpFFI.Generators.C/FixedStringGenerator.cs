using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;
using SharpFFI.Generators.Core;

namespace SharpFFI.Generators.C;

[Generator(LanguageNames.CSharp)]
public class FixedStringGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var fixedStringDeclarations = context.SyntaxProvider.ForAttributeWithMetadataName(
            fullyQualifiedMetadataName: FixedStringAttributeData.AttributeFullName,
            predicate: static (syntaxNode, _) => syntaxNode is StructDeclarationSyntax structDeclaration
                && TypeModifierValidator.FixedString.IsValid(structDeclaration)
                && FixedStringNameValidator.IsValid(structDeclaration),
            transform: static (context, _) =>
            {
                var symbol = (INamedTypeSymbol)context.TargetSymbol;
                FixedStringNameValidator.TryParse(symbol.Name, out var size, out var isReadOnly);

                return new FixedStringGenerationContext(
                    symbol.GetNamespace(),
                    symbol.GetRawName(),
                    symbol.GetTypeDeclarationName(),
                    symbol.GetHintName("FixedString"),
                    size,
                    isReadOnly);
            });

        context.RegisterSourceOutput(fixedStringDeclarations, static (productionContext, context) => productionContext.AddSource(context.HintName, SourceText.From(GenerateSourceCode(context), Encoding.UTF8)));
    }

    private static string GenerateSourceCode(FixedStringGenerationContext context)
    {
        var rawName = context.RawStructName;
        var name = context.StructName;
        var capacity = context.Capacity;
        var isReadOnly = context.IsReadOnly;
        var builder = new SourceCodeBuilder();

        builder.AppendAutoGenerated()
               .AppendNullableEnable()
               .AppendWarningDisable("CS9084")
               .AppendUsings("System", "System.Text", "System.Diagnostics", "System.Runtime.InteropServices", "System.Runtime.CompilerServices", "SharpFFI.Primitives.Utf8");

        using (builder.BeginNamespaceScope(context.StructNamespace))
        {
            builder.AppendLine("[DebuggerDisplay(\"{ToString(),raw}\")]")
                   .AppendLine("[StructLayout(LayoutKind.Sequential)]");

            var modifiers = isReadOnly ? "readonly partial" : "partial";
            using (builder.BeginTypeScope("struct", $"{name} : IEquatable<{name}>", modifiers))
            {
                builder.AppendBlock($$"""
                    public const int Capacity = {{capacity}};

                    {{(isReadOnly ? "private readonly Buffer _buffer;" : "private Buffer _buffer;")}}

                    public static {{name}} Empty
                    {
                        [MethodImpl(MethodImplOptions.AggressiveInlining)]
                        get => default;
                    }

                    [MethodImpl(MethodImplOptions.AggressiveInlining)]
                    public {{rawName}}(string? value) : this()
                    {
                        if (string.IsNullOrEmpty(value))
                            return;

                        var destination = MemoryMarshal.CreateSpan(ref Unsafe.AsRef(in _buffer.Item0), Capacity);
                        var bytesWritten = Encoding.UTF8.GetBytes(value.AsSpan(), destination.Slice(0, Capacity - 1));
                        destination[bytesWritten] = 0;
                    }

                    [MethodImpl(MethodImplOptions.AggressiveInlining)]
                    public {{rawName}}(ReadOnlySpan<byte> value) : this()
                    {
                        if (value.IsEmpty)
                            return;

                        var destination = MemoryMarshal.CreateSpan(ref Unsafe.AsRef(in _buffer.Item0), Capacity);
                        var copyLength = Math.Min(value.Length, Capacity - 1);
                        value.Slice(0, copyLength).CopyTo(destination);
                        destination[copyLength] = 0;
                    }

                    public readonly int Length
                    {
                        [MethodImpl(MethodImplOptions.AggressiveInlining)]
                        get => Utf8StringView.GetLength(AsReadOnlySpan());
                    }

                    public readonly bool IsEmpty
                    {
                        [MethodImpl(MethodImplOptions.AggressiveInlining)]
                        get => _buffer.Item0 == 0;
                    }
                    """);

                if (!isReadOnly)
                {
                    builder.AppendLine()
                           .AppendBlock("""
                                        public ref byte this[int index]
                                        {
                                            [MethodImpl(MethodImplOptions.AggressiveInlining)]
                                            get => ref AsSpan()[index];
                                        }

                                        [MethodImpl(MethodImplOptions.AggressiveInlining)]
                                        public void Clear() => AsSpan().Clear();

                                        [MethodImpl(MethodImplOptions.AggressiveInlining)]
                                        public Span<byte> AsSpan() => MemoryMarshal.CreateSpan(ref _buffer.Item0, Capacity);

                                        [MethodImpl(MethodImplOptions.AggressiveInlining)]
                                        public Utf8StringView AsView() => Utf8StringView.FromUtf8Span(AsSpan().Slice(0, Length));
                                        """);
                }
                else
                {
                    builder.AppendLine()
                           .AppendBlock("""
                                        public readonly byte this[int index]
                                        {
                                            [MethodImpl(MethodImplOptions.AggressiveInlining)]
                                            get => AsReadOnlySpan()[index];
                                        }
                                        """);
                }

                builder.AppendLine()
                       .AppendBlock($$"""
                           [MethodImpl(MethodImplOptions.AggressiveInlining)]
                           public readonly ReadOnlySpan<byte> AsReadOnlySpan() => MemoryMarshal.CreateSpan(ref Unsafe.AsRef(in _buffer.Item0), Capacity);

                           [MethodImpl(MethodImplOptions.AggressiveInlining)]
                           public readonly ReadOnlyUtf8StringView AsReadOnlyView() => ReadOnlyUtf8StringView.FromUtf8Span(AsReadOnlySpan().Slice(0, Length));

                           [MethodImpl(MethodImplOptions.AggressiveInlining)]
                           public readonly void CopyTo(Span<byte> destination) => AsReadOnlySpan().Slice(0, Length).CopyTo(destination);

                           [MethodImpl(MethodImplOptions.AggressiveInlining)]
                           public readonly bool TryCopyTo(Span<byte> destination) => AsReadOnlySpan().Slice(0, Length).TryCopyTo(destination);

                           [MethodImpl(MethodImplOptions.AggressiveInlining)]
                           public readonly Utf8CharEnumerator GetEnumerator() => AsReadOnlyView().GetEnumerator();

                           [MethodImpl(MethodImplOptions.AggressiveInlining)]
                           public readonly bool Equals({{name}} other) => AsReadOnlyView().Equals(other.AsReadOnlyView());

                           [MethodImpl(MethodImplOptions.AggressiveInlining)]
                           public readonly override bool Equals(object? obj) => obj is {{name}} other && Equals(other);

                           [MethodImpl(MethodImplOptions.AggressiveInlining)]
                           public readonly override int GetHashCode() => Utf8StringView.GetHashCode(AsReadOnlyView().Span);

                           [MethodImpl(MethodImplOptions.AggressiveInlining)]
                           public readonly override string ToString() => IsEmpty ? string.Empty : Encoding.UTF8.GetString(AsReadOnlyView().Span);

                           [MethodImpl(MethodImplOptions.AggressiveInlining)]
                           public static bool operator ==({{name}} left, {{name}} right) => left.Equals(right);

                           [MethodImpl(MethodImplOptions.AggressiveInlining)]
                           public static bool operator !=({{name}} left, {{name}} right) => !left.Equals(right);

                           [MethodImpl(MethodImplOptions.AggressiveInlining)]
                           public static implicit operator ReadOnlySpan<byte>(in {{name}} str) => str.AsReadOnlySpan();

                           [MethodImpl(MethodImplOptions.AggressiveInlining)]
                           public static implicit operator ReadOnlyUtf8StringView(in {{name}} str) => str.AsReadOnlyView();
                           """);

                builder.AppendLine()
                       .AppendFixedBuffer(capacity, "byte");
            }
        }

        return builder.ToString();
    }

    private readonly record struct FixedStringGenerationContext(
        string StructNamespace,
        string RawStructName,
        string StructName,
        string HintName,
        int Capacity,
        bool IsReadOnly);
}
