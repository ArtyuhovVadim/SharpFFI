using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;
using SharpFFI.Generators.Core;

namespace SharpFFI.Generators.C;

[Generator(LanguageNames.CSharp)]
public class FixedArrayGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var fixedArrayDeclarations = context.SyntaxProvider.ForAttributeWithMetadataName(
            fullyQualifiedMetadataName: FixedArrayAttributeData.AttributeFullName,
            predicate: static (syntaxNode, _) => syntaxNode is StructDeclarationSyntax structDeclaration && PartialValidator.IsValid(structDeclaration),
            transform: static (context, _) =>
            {
                var symbol = (INamedTypeSymbol)context.TargetSymbol;
                var attribute = FixedArrayAttributeData.FromAttributeData(context.Attributes[0]);

                var name = $"{symbol.Name}<T>";
                var @namespace = symbol.ContainingNamespace.IsGlobalNamespace ? string.Empty : symbol.ContainingNamespace.ToDisplayString();

                return new FixedArrayGenerationContext(@namespace, name, attribute);
            });

        context.RegisterSourceOutput(fixedArrayDeclarations, static (productionContext, context) => productionContext.AddSource($"{context.StructName.Replace('<', '{').Replace('>', '}')}.FixedArray.g.cs", SourceText.From(GenerateSourceCode(context), Encoding.UTF8)));
    }

    private static string GenerateSourceCode(FixedArrayGenerationContext context)
    {
        var builder = new SourceCodeBuilder();

        builder.AppendAutoGenerated()
               .AppendLine()
               .AppendWarningDisable("CS9084")
               .AppendLine()
               .AppendUsing("System")
               .AppendUsing("System.Runtime.InteropServices")
               .AppendUsing("System.Runtime.CompilerServices")
               .AppendLine();

        if (context.IsGlobalNamespace)
        {
            GenerateStructSourceCode(builder, context);
        }
        else
        {
            builder.AppendNamespace(context.StructNamespace);

            using (builder.BeginScope())
            {
                GenerateStructSourceCode(builder, context);
            }
        }

        return builder.ToString();
    }

    private static void GenerateStructSourceCode(SourceCodeBuilder builder, FixedArrayGenerationContext context)
    {
        builder.AppendLine("[StructLayout(LayoutKind.Sequential)]")
               .AppendLine($"unsafe partial struct {context.StructName}");

        using (builder.BeginScope())
        {
            for (var i = 0; i < context.FixedArrayAttribute.Length; i++)
                builder.AppendLine($"private T _item{i};");

            builder.AppendLine()
                   .AppendLine($"public static {context.StructName} Empty");

            using (builder.BeginScope())
            {
                builder.AppendAgressiveInlining()
                       .AppendLine("get => default;");
            }

            builder.AppendLine()
                   .AppendLine("public readonly int Capacity");

            using (builder.BeginScope())
            {
                builder.AppendAgressiveInlining()
                       .AppendLine($"get => {context.FixedArrayAttribute.Length};");
            }

            builder.AppendLine()
                   .AppendLine("public readonly ref T this[int index]");

            using (builder.BeginScope())
            {
                builder.AppendAgressiveInlining()
                       .AppendLine("get");

                using (builder.BeginScope())
                {
                    builder.AppendLine("if ((uint)index >= (uint)Capacity)")
                           .AppendLine("    ThrowOverflow();")
                           .AppendLine()
                           .AppendLine("return ref Unsafe.Add(ref Unsafe.AsRef(in _item0), index);");
                }
            }

            builder.AppendLine()
                   .AppendAgressiveInlining()
                   .AppendLine("public Span<T> AsSpan() => new(Unsafe.AsPointer(ref Unsafe.AsRef(in _item0)), Capacity);")
                   .AppendLine()
                   .AppendAgressiveInlining()
                   .AppendLine("public ReadOnlySpan<T> AsReadOnlySpan() => new(Unsafe.AsPointer(ref Unsafe.AsRef(in _item0)), Capacity);")
                   .AppendLine()
                   .AppendAgressiveInlining()
                   .AppendLine("public Span<T>.Enumerator GetEnumerator() => AsSpan().GetEnumerator();")
                   .AppendLine()
                   .AppendLine($"private static void ThrowOverflow() => throw new IndexOutOfRangeException(\"Item should fit into {context.StructName}.\");")
                   .AppendLine();
        }
    }

    private readonly record struct FixedArrayGenerationContext(string StructNamespace, string StructName, FixedArrayAttributeData FixedArrayAttribute)
    {
        public bool IsGlobalNamespace => string.IsNullOrEmpty(StructNamespace);
    }
}