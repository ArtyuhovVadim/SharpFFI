using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;
using SharpFFI.Generators.Core;

namespace SharpFFI.Generators.C;

[Generator(LanguageNames.CSharp)]
public class FixedArrayGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var fixedArrayDeclarations = context.SyntaxProvider.ForAttributeWithMetadataName(
            fullyQualifiedMetadataName: FixedArrayAttributeData.AttributeFullName,
            predicate: static (syntaxNode, _) => syntaxNode is StructDeclarationSyntax structDeclaration && TypeModifierValidator.FixedArray.IsValid(structDeclaration),
            transform: static (context, _) =>
            {
                var symbol = (INamedTypeSymbol)context.TargetSymbol;
                var attribute = FixedArrayAttributeData.FromAttributeData(context.Attributes[0]);

                return new FixedArrayGenerationContext(
                    symbol.GetNamespace(),
                    symbol.GetRawName(),
                    symbol.GetTypeDeclarationName(),
                    symbol.GetHintName("FixedArray"),
                    attribute);
            });

        context.RegisterSourceOutput(fixedArrayDeclarations, static (productionContext, context) => productionContext.AddSource(context.HintName, SourceText.From(GenerateSourceCode(context), Encoding.UTF8)));
    }

    private static string GenerateSourceCode(FixedArrayGenerationContext context)
    {
        var rawName = context.RawStructName;
        var name = context.StructName;
        var length = context.FixedArrayAttribute.Length;
        var builder = new SourceCodeBuilder();

        builder.AppendAutoGenerated()
               .AppendNullableEnable()
               .AppendWarningDisable("CS9084")
               .AppendUsings("System", "System.Diagnostics", "System.Runtime.InteropServices", "System.Runtime.CompilerServices");

        using (builder.BeginNamespaceScope(context.StructNamespace))
        {
            builder.AppendLine("[DebuggerDisplay(\"Length = {Length}\")]")
                   .AppendLine("[StructLayout(LayoutKind.Sequential)]");

            using (builder.BeginTypeScope("struct", name))
            {
                builder.AppendBlock($$"""
                    public const int Length = {{length}};

                    private Buffer _buffer;

                    public static {{name}} Empty
                    {
                        [MethodImpl(MethodImplOptions.AggressiveInlining)]
                        get => default;
                    }

                    [MethodImpl(MethodImplOptions.AggressiveInlining)]
                    public {{rawName}}(ReadOnlySpan<T> items) : this() => items.CopyTo(AsSpan());

                    public ref T this[int index]
                    {
                        [MethodImpl(MethodImplOptions.AggressiveInlining)]
                        get => ref AsSpan()[index];
                    }

                    [MethodImpl(MethodImplOptions.AggressiveInlining)]
                    public void Clear() => AsSpan().Clear();

                    [MethodImpl(MethodImplOptions.AggressiveInlining)]
                    public void Fill(T value) => AsSpan().Fill(value);

                    [MethodImpl(MethodImplOptions.AggressiveInlining)]
                    public Span<T> AsSpan() => MemoryMarshal.CreateSpan(ref _buffer.Item0, Length);

                    [MethodImpl(MethodImplOptions.AggressiveInlining)]
                    public readonly ReadOnlySpan<T> AsReadOnlySpan() => MemoryMarshal.CreateSpan(ref Unsafe.AsRef(in _buffer.Item0), Length);

                    [MethodImpl(MethodImplOptions.AggressiveInlining)]
                    public Span<T> Slice(int start) => AsSpan().Slice(start);

                    [MethodImpl(MethodImplOptions.AggressiveInlining)]
                    public Span<T> Slice(int start, int length) => AsSpan().Slice(start, length);

                    [MethodImpl(MethodImplOptions.AggressiveInlining)]
                    public readonly void CopyTo(Span<T> destination) => AsReadOnlySpan().CopyTo(destination);

                    [MethodImpl(MethodImplOptions.AggressiveInlining)]
                    public readonly bool TryCopyTo(Span<T> destination) => AsReadOnlySpan().TryCopyTo(destination);

                    [MethodImpl(MethodImplOptions.AggressiveInlining)]
                    public static implicit operator ReadOnlySpan<T>(in {{name}} array) => array.AsReadOnlySpan();

                    [MethodImpl(MethodImplOptions.AggressiveInlining)]
                    public readonly ReadOnlySpan<T>.Enumerator GetEnumerator() => AsReadOnlySpan().GetEnumerator();

                    public readonly override string ToString() => $"{{rawName}}<{typeof(T).Name}>[{Length}]";
                    """);

                builder.AppendLine()
                       .AppendFixedBuffer(length);
            }
        }

        return builder.ToString();
    }

    private readonly record struct FixedArrayGenerationContext(
        string StructNamespace,
        string RawStructName,
        string StructName,
        string HintName,
        FixedArrayAttributeData FixedArrayAttribute);
}
