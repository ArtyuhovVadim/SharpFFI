using System.Text;

namespace SharpFFI.Generators.Core;

public class SourceCodeBuilder
{
    private readonly StringBuilder _stringBuilder = new();
    private int _level;

    public SourceCodeBuilder Append(string line)
    {
        _stringBuilder.Append(line);
        return this;
    }

    public SourceCodeBuilder AppendLine(string line)
    {
        AppendCurrentIndent();
        _stringBuilder.AppendLine(line);
        return this;
    }

    public SourceCodeBuilder AppendLine()
    {
        _stringBuilder.AppendLine();
        return this;
    }

    public SourceCodeBuilder AppendIndent(int count)
    {
        _stringBuilder.Append(' ', count * 4);
        return this;
    }

    public SourceCodeBuilder AppendAutoGenerated() => AppendLine("// <auto-generated />");

    public SourceCodeBuilder AppendNullableEnable() => AppendLine("#nullable enable");

    public SourceCodeBuilder AppendWarningDisable(string warningName) => AppendLine($"#pragma warning disable {warningName}");

    public SourceCodeBuilder AppendUsing(string usingName) => AppendLine($"using {usingName};");

    public SourceCodeBuilder AppendAgressiveInlining() => AppendLine("[MethodImpl(MethodImplOptions.AggressiveInlining)]");

    public SourceCodeBuilder AppendFileScopedNamespace(string namespaceName) => AppendLine($"namespace {namespaceName};");

    public SourceCodeBuilder AppendNamespace(string namespaceName) => AppendLine($"namespace {namespaceName}");

    public SourceCodeBuilder AppendCurrentIndent()
    {
        if (_level == 0)
            return this;

        _stringBuilder.Append(' ', _level * 4);
        return this;
    }

    public IDisposable BeginScope() => new Scope(this);

    public override string ToString() => _stringBuilder.ToString();

    public class Scope : IDisposable
    {
        private readonly SourceCodeBuilder _builder;

        public Scope(SourceCodeBuilder builder)
        {
            _builder = builder;
            _builder.AppendLine("{");
            _builder._level++;
        }

        public void Dispose()
        {
            _builder._level--;
            _builder.AppendLine("}");
        }
    }
}